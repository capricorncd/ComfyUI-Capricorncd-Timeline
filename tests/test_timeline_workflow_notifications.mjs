import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../js/CapTimelineEditorApp.js',import.meta.url),'utf8');
const start=source.indexOf('    _writeProjectJson(json) {');
const end=source.indexOf('\n    }',start)+6;
const write=new Function('return ({'+source.slice(start,end)+'})._writeProjectJson')();
const calls=[];
const widgets=[{name:'project_json',value:'old'},{name:'storyboard_json',value:'story'},{name:'button',serialize:false}];
const node={widgets,properties:{},graph:{beforeChange(){calls.push('before');},afterChange(){calls.push(['after',widgets[0].value,node.properties.cat_named.project_json]);}},setDirtyCanvas(){}};
const editor={node,_isNodeOnLiveGraph:()=>true,_w:name=>widgets.find(w=>w.name===name)};
write.call(editor,'new');
assert.deepEqual(calls,['before',['after','new','new']]);
assert.deepEqual(node.widgets_values,['new','story']);
calls.length=0;
write.call(editor,'new');
assert.deepEqual(calls,[],'unchanged autosave must not create workflow changes');
widgets[1].value='story changed';
write.call(editor,'new');
assert.equal(calls.length,2,'storyboard changes notify too');
calls.length=0;
editor._isNodeOnLiveGraph=()=>false;
write.call(editor,'wrong tab');
assert.equal(widgets[0].value,'new');
assert.deepEqual(calls,[]);
console.log('Workflow notifications capture project/storyboard changes and skip unchanged or inactive editors.');
