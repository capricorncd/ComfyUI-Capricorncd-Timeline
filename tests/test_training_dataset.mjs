import assert from 'node:assert/strict';
import { scenesFromPoints, windowBounds, normalizeSelection, selectedClips, copyDatasetData } from '../js/training_dataset/model.js';
const scenes=scenesFromPoints([0,2,2,8,NaN,-1,40],12);
assert.deepEqual(scenes.map(s=>[s.start,s.end]),[[0,2],[2,8],[8,12]]);
assert.equal(windowBounds(scenes[0]).eligible,false);
assert.equal(windowBounds(scenes[1]).eligible,true);
assert.equal(windowBounds({start:0,end:124/24}).eligible,true);
assert.equal(windowBounds({start:.01,end:124/24}).eligible,false);
scenes[1].selected=true;scenes[1].caption='kept';
assert.equal(scenesFromPoints([2,8],12,scenes)[1].caption,'kept');
assert.equal(scenesFromPoints([2,4,8],12,scenes).some(s=>s.caption==='kept'),false);
const sources=[{token:'video',segments:scenes}];
scenes[0].selected=true;
normalizeSelection(sources,124);
assert.equal(selectedClips(sources,124).length,1);
assert.equal(selectedClips(sources,124)[0].token,'video');
normalizeSelection(sources,345);
assert.equal(selectedClips(sources,345).length,0);
const state={settings:{width:512,height:256},sources:[{path:'video.mp4',segments:[{start:0,end:6,caption:'肤色与色调',selected:true,crop:{zoom:1.5,x:.3,y:0}}]}]};
const reactive=value=>value && typeof value==='object'?new Proxy(value,{get:(target,key)=>reactive(Reflect.get(target,key))}):value;
const proxy=reactive(state);
assert.throws(()=>structuredClone(proxy),{name:'DataCloneError'});
const reopened=copyDatasetData(proxy);
assert.deepEqual(reopened,state);
const undo=copyDatasetData(proxy.sources[0].segments);
const saved=copyDatasetData({...proxy,sources:[...proxy.sources]});
reopened.sources[0].segments[0].crop.zoom=2;
state.sources[0].segments[0].caption='changed';
assert.equal(undo[0].caption,'肤色与色调');
assert.equal(saved.sources[0].segments[0].caption,'肤色与色调');
assert.equal(saved.sources[0].segments[0].crop.zoom,1.5);
assert.deepEqual(structuredClone(saved),saved);
console.log('Training dataset selection, boundaries and reactive snapshot tests passed');
