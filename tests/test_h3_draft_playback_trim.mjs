import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {h3TimingFromFilename} from '../js/editor/H3Timing.js';
const source=readFileSync(process.argv[2] || new URL('../js/CapTimelineEditorApp.js',import.meta.url),'utf8');
const start=source.indexOf('    _draftPreviewVideos(meta, clip) {');
const end=source.indexOf('\n    _toggleDraftPreview()',start);
const preview=new Function('h3TimingFromFilename', 'return ({'+source.slice(start,end)+'})._draftPreviewVideos')(h3TimingFromFilename);
const row={id:'draft',enabled:true,fps:24,frames:192,file:'sample__h3v2_c22_r192_h0_t9_f24000_s1_n7.mp4'};
let result=preview({h3Drafts:[row]},{duration:7});
assert.equal(result[0].trim_in_sec,15/24,'exclude context but retain carried visible tail');
assert.equal(result[0].trim_out_sec-result[0].trim_in_sec,7,'keep exact timeline duration');
result=preview({h3Drafts:[{...row,file:'sample__h3v1_c22_r192_h2_t0_f24000_s1.mp4'}]},{duration:7});
assert.equal(result[0].trim_in_sec,1,'v1 context and additional head trim');
result=preview({h3Drafts:[{...row,frames:175,file:'sample__h3v2_c0_r175_h0_t7_f24000_s1_n0.mp4'}]},{duration:7});
assert.equal(result[0].trim_in_sec,0);assert.equal(result[0].trim_out_sec,7);
result=preview({h3Drafts:[{...row,keyframe_segment:{start_frame:24,end_frame:144,fps:24,output_fps:24,trim_frames:22}}]},{duration:7});
assert.equal(result[0].edit_start_sec,1);assert.equal(result[0].trim_in_sec,22/24);assert.equal(result[0].trim_out_sec-result[0].trim_in_sec,5);
result=preview({h3Drafts:[{...row,file:'legacy.mp4'}]},{duration:7});assert.equal(result[0].trim_in_sec,0);
assert.deepEqual(preview({h3Drafts:[{...row,enabled:false}]},{duration:7}),[]);
console.log('Passed: H3 v2 carry, v1 context/head, independent clips, keyframe spans, legacy previews, disabled versions');
